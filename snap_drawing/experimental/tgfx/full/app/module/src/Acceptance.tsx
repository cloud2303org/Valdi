import { StatefulComponent } from 'valdi_core/src/Component';
import { makeAssetFromBytes } from 'valdi_core/src/Asset';
import { GeometricPathBuilder, GeometricPathScaleType } from 'valdi_core/src/GeometricPath';
import { onIdleInterruptible } from 'valdi_core/src/utils/OnIdle';
import { createManagedContext } from 'drawing/src/ManagedContextFactory';
import { createBitmap, decodeBitmap } from 'drawing/src/BitmapFactory';
import { BitmapAlphaType, BitmapColorType, IBitmap, ImageEncoding } from 'drawing/src/IBitmap';
import { IManagedContext, IManagedContextFrame } from 'drawing/src/IManagedContext';
import { Asset } from 'valdi_tsx/src/Asset';
import { FIXTURES, PROVENANCE } from './Fixtures';
import res from 'tgfx_acceptance/res';

/**
 * @ViewModel
 * @ExportModel
 */
export interface AcceptanceViewModel {}

/**
 * Generated by the actual Node codegen; hosts compile the emitted Kotlin/ObjC.
 * @Context
 * @ExportModel
 */
export interface AcceptanceContext {
  report: (event: string) => void;
}

const WIDTH = 160;
const HEIGHT = 120;
const CASE_IDS = [
  'composition', 'shape', 'label-iiii', 'label-mmmm',
  'bitmap-bytes', 'bitmap-catalog', 'svg', 'lottie-t0', 'lottie-t1',
];
type RGBA = readonly [number, number, number, number];
interface Assertion { name: string; passed: boolean; actual: string; }
interface CaseResult {
  id: string;
  passed: boolean;
  assertions: Assertion[];
  assets: { tracked: number; loaded: number; errors: string[]; };
  pixelHash: string;
}
interface State { status: string; preview?: Asset; }
interface Capture { pixels: Uint8Array; png: ArrayBuffer; result: CaseResult; }
const WHITE: RGBA = [255, 255, 255, 255];
const triangle = new GeometricPathBuilder(1, 1, GeometricPathScaleType.Fill)
  .moveTo(0, 1).lineTo(0.5, 0).lineTo(1, 1).close().build();

// Deliberately inspect the executing engine, rather than trusting a build flag.
declare const globalThis: {
  HermesInternal?: { getRuntimeProperties?: () => { [key: string]: unknown } };
};

function check(list: Assertion[], name: string, passed: boolean, actual: unknown): void {
  list.push({ name, passed, actual: String(actual) });
}
function pixel(pixels: Uint8Array, x: number, y: number): RGBA {
  const offset = (y * WIDTH + x) * 4;
  return [pixels[offset], pixels[offset + 1], pixels[offset + 2], pixels[offset + 3]];
}
function expectPixel(list: Assertion[], pixels: Uint8Array, name: string,
                     x: number, y: number, expected: RGBA, tolerance = 5): void {
  const actual = pixel(pixels, x, y);
  check(list, name, actual.every((value, index) => Math.abs(value - expected[index]) <= tolerance),
    `${x},${y}: ${actual.join(',')} expected ${expected.join(',')} tolerance ${tolerance}`);
}
function hash(pixels: Uint8Array): string {
  let value = 2166136261;
  for (const byte of pixels) value = Math.imul(value ^ byte, 16777619) >>> 0;
  return value.toString(16);
}
function base64(bytes: Uint8Array): string {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  let output = '';
  for (let i = 0; i < bytes.length; i += 3) {
    const value = (bytes[i] << 16) | ((bytes[i + 1] ?? 0) << 8) | (bytes[i + 2] ?? 0);
    output += alphabet[(value >>> 18) & 63] + alphabet[(value >>> 12) & 63]
      + (i + 1 < bytes.length ? alphabet[(value >>> 6) & 63] : '=')
      + (i + 2 < bytes.length ? alphabet[value & 63] : '=');
  }
  return output;
}
function fixture(name: keyof typeof FIXTURES): Uint8Array {
  return new Uint8Array(FIXTURES[name]);
}
async function bounded<T>(operation: Promise<T>, label: string): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    return await Promise.race([operation, new Promise<T>((_resolve, reject) => {
      timer = setTimeout(() => reject(new Error(`${label}: 10000ms timeout`)), 10000);
    })]);
  } finally {
    if (timer !== undefined) clearTimeout(timer);
  }
}
const idle = () => bounded(new Promise<void>(resolve => onIdleInterruptible(resolve)), 'idle');

/**
 * @Component
 * @ExportModel
 */
export class AcceptanceApp extends StatefulComponent<AcceptanceViewModel, State, AcceptanceContext> {
  state: State = { status: 'WAITING for layout' };
  private started = false;
  private destroyed = false;
  private results: CaseResult[] = [];
  private active?: IManagedContext;

  onDestroy(): void {
    this.destroyed = true;
    this.active?.dispose();
    this.active = undefined;
  }

  onRender(): void {
    <view width="100%" height="100%" backgroundColor="white" padding={8}>
      <label value={this.state.status} font="system-bold 16" color="black" numberOfLines={0} />
      <image src={this.state.preview} width={WIDTH} height={HEIGHT} objectFit="contain" />
    </view>;
    if (!this.started) {
      this.started = true;
      this.renderer.onLayoutComplete(() => { void this.run(); });
    }
  }

  private emit(event: object): void {
    if (this.destroyed) throw new Error('Acceptance component destroyed before completion');
    this.context.report(JSON.stringify(event));
  }

  private async capture(id: string): Promise<Capture> {
    if (this.destroyed) throw new Error('Acceptance component destroyed');
    const assertions: Assertion[] = [];
    const assets = { tracked: 0, loaded: 0, errors: [] as string[] };
    // Managed ImageLayerClass/AnimatedImageLayerClass bind onAssetLoad through
    // AssetAttributes. Decode evidence comes from rendered pixels and the real
    // PNG decode below; those managed classes do not bind onImageDecoded.
    const onLoad = (success: boolean, error?: string) => {
      if (success) assets.loaded++;
      else assets.errors.push(error || 'onAssetLoad returned false');
    };
    const asset = id === 'svg' ? makeAssetFromBytes(fixture('svg'))
      : id.startsWith('lottie') ? makeAssetFromBytes(fixture('lottie'))
        : id === 'bitmap-bytes' ? makeAssetFromBytes(fixture('png')) : undefined;
    const context = createManagedContext({ useAsyncPath: true });
    this.active = context;
    let bitmap: IBitmap | undefined;
    let frame: IManagedContextFrame | undefined;
    try {
      context.render(() => {
        <view width={WIDTH} height={HEIGHT} backgroundColor="white">
          {id === 'composition' && <view position="absolute" left={10} top={10}
            width={60} height={60} backgroundColor="#ff0000" />}
          {id === 'composition' && <view position="absolute" left={40} top={40}
            width={60} height={60} backgroundColor="#0000ff" opacity={0.5} />}
          {id === 'composition' && <view position="absolute" left={110} top={10}
            width={30} height={30} slowClipping>
            <view position="absolute" left={20} top={0} width={50} height={20} backgroundColor="#ffff00" />
          </view>}
          {id === 'shape' && <shape position="absolute" left={20} top={10}
            width={100} height={100} path={triangle} fillColor="#00aa44" />}
          {id.startsWith('label-') && <label position="absolute" left={8} top={8}
            width={144} height={64} font="system 32" color="#000000"
            value={id === 'label-iiii' ? 'IIII' : 'MMMM'} />}
          {(id === 'svg' || id.startsWith('bitmap-')) && <image
            src={id === 'bitmap-catalog' ? res.pattern : asset} position="absolute"
            left={0} top={0} width={120} height={80} objectFit="fill"
            onAssetLoad={onLoad} />}
          {id.startsWith('lottie') && <animatedimage src={asset} position="absolute"
            left={0} top={0} width={120} height={120} objectFit="fill"
            advanceRate={0} loop={false} animationStartTime={0} animationEndTime={2}
            currentTime={id === 'lottie-t0' ? 0 : 1}
            onAssetLoad={onLoad} />}
        </view>;
      });
      await bounded(context.layout(WIDTH, HEIGHT, false), `${id} layout`);
      // Layout first: it starts asset work for the real tree. Drain host+JS work
      // before reading the tracker, and again before drawing callbacks/results.
      await idle();
      const loaded = await bounded(context.onAllAssetsLoaded(), `${id} assets`);
      assets.tracked = loaded.loadedAssetsCount;
      assets.errors.push(...(loaded.errors ?? []));
      await idle();
      if (this.destroyed) throw new Error('Destroyed during asset load');
      context.processFrame(0);
      ({ frame } = await bounded(context.draw(), `${id} draw`));
      bitmap = createBitmap({ width: WIDTH, height: HEIGHT, rowBytes: WIDTH * 4,
        colorType: BitmapColorType.RGBA8888, alphaType: BitmapAlphaType.Premul });
      frame.rasterInto(bitmap, true);
      const pixels = bitmap.accessPixels(view => new Uint8Array(view.buffer).slice());
      check(assertions, 'RGBA readback size', pixels.length === WIDTH * HEIGHT * 4, pixels.length);
      if (id === 'composition') {
        expectPixel(assertions, pixels, 'red layer', 20, 20, [255, 0, 0, 255]);
        expectPixel(assertions, pixels, 'source-over opacity', 50, 50, [127, 0, 128, 255]);
        expectPixel(assertions, pixels, 'clip interior', 135, 20, [255, 255, 0, 255]);
        expectPixel(assertions, pixels, 'clip exterior', 145, 20, WHITE);
      } else if (id === 'shape') {
        expectPixel(assertions, pixels, 'triangle interior', 70, 70, [0, 170, 68, 255]);
        expectPixel(assertions, pixels, 'triangle exterior', 25, 15, WHITE);
      } else if (id.startsWith('label-')) {
        let ink = 0;
        let outside = 0;
        for (let y = 0; y < HEIGHT; y++) for (let x = 0; x < WIDTH; x++) {
          const p = pixel(pixels, x, y);
          if (p[0] < 100 && p[1] < 100 && p[2] < 100) {
            if (x >= 8 && x < 152 && y >= 8 && y < 72) ink++;
            else outside++;
          }
        }
        check(assertions, 'visible label glyph coverage', ink > 70 && ink < 4000, ink);
        check(assertions, 'label stays in bounds', outside === 0, outside);
      } else if (id.startsWith('bitmap-')) {
        const tolerance = id === 'bitmap-catalog' ? 50 : 5;
        expectPixel(assertions, pixels, 'bitmap red', 5, 5, [255, 0, 0, 255], tolerance);
        expectPixel(assertions, pixels, 'bitmap green', 115, 5, [0, 255, 0, 255], tolerance);
        expectPixel(assertions, pixels, 'bitmap blue', 5, 75, [0, 0, 255, 255], tolerance);
        expectPixel(assertions, pixels, 'bitmap white', 115, 75, WHITE, tolerance);
      } else if (id === 'svg') {
        expectPixel(assertions, pixels, 'SVG red quadrant', 10, 10, [255, 59, 48, 255]);
        expectPixel(assertions, pixels, 'SVG green quadrant', 110, 10, [52, 199, 89, 255]);
        expectPixel(assertions, pixels, 'SVG blue quadrant', 10, 70, [0, 122, 255, 255]);
        expectPixel(assertions, pixels, 'SVG white center', 60, 40, WHITE);
      } else {
        expectPixel(assertions, pixels, 'Lottie blue center', 60, 60, [0, 122, 255, 255], 5);
        expectPixel(assertions, pixels, 'Lottie time-dependent radius', 94, 60,
          id === 'lottie-t0' ? WHITE : [0, 122, 255, 255], 8);
        expectPixel(assertions, pixels, 'Lottie outside', 112, 60, WHITE);
        if (id === 'lottie-t1') {
          expectPixel(assertions, pixels, 'Lottie yellow stroke', 102, 60, [255, 204, 0, 255], 12);
        }
      }
      if (asset || id === 'bitmap-catalog') {
        check(assertions, 'asset tracked', assets.tracked >= 1, assets.tracked);
        check(assertions, 'asset success callback', assets.loaded >= 1, assets.loaded);
      }
      check(assertions, 'no asset errors', assets.errors.length === 0, JSON.stringify(assets.errors));
      const png = bitmap.encode(ImageEncoding.PNG, 1);
      // Exercise actual PNG decoding and compare content, not just PNG length.
      const roundTrip = decodeBitmap(png);
      try {
        const info = roundTrip.getInfo();
        check(assertions, 'PNG dimensions', info.width === WIDTH && info.height === HEIGHT,
          `${info.width}x${info.height}`);
        const supported = info.colorType === BitmapColorType.RGBA8888 || info.colorType === BitmapColorType.BGRA8888;
        check(assertions, 'PNG 8-bit color format', supported, info.colorType);
        if (supported) {
          const decoded = roundTrip.accessPixels(view => {
            const packed = new Uint8Array(WIDTH * HEIGHT * 4);
            for (let y = 0; y < HEIGHT; y++) {
              packed.set(new Uint8Array(view.buffer, view.byteOffset + y * info.rowBytes, WIDTH * 4), y * WIDTH * 4);
            }
            if (info.colorType === BitmapColorType.BGRA8888) {
              for (let i = 0; i < packed.length; i += 4) {
                const blue = packed[i];
                packed[i] = packed[i + 2];
                packed[i + 2] = blue;
              }
            }
            return packed;
          });
          check(assertions, 'PNG content round trip', hash(decoded) === hash(pixels), hash(decoded));
        }
      } finally { roundTrip.dispose(); }
      return { pixels, png, result: { id, assertions, assets,
        passed: assertions.length > 0 && assertions.every(assertion => assertion.passed), pixelHash: hash(pixels) } };
    } finally {
      frame?.dispose();
      bitmap?.dispose();
      if (this.active === context) {
        this.active = undefined;
        context.dispose();
      }
    }
  }

  private async run(): Promise<void> {
    const properties = globalThis.HermesInternal?.getRuntimeProperties;
    let engine = { verified: false, name: 'unknown', properties: {} as object };
    try {
      if (typeof properties !== 'function') throw new Error('Executing JS engine has no HermesInternal.getRuntimeProperties');
      const actualProperties = properties();
      if (actualProperties['OSS Release Version'] !== PROVENANCE.hermesRelease ||
          !(Number(actualProperties['Bytecode Version']) > 0))
        throw new Error(`Hermes runtime version disagrees with the pinned compiler contract: ${JSON.stringify(actualProperties)}`);
      engine = { verified: true, name: 'Hermes', properties: actualProperties };
      this.emit({ schema: 1, kind: 'started', status: 'RUNNING', engine, provenance: PROVENANCE, expectedCaseIds: CASE_IDS });
      let textPixels: Uint8Array | undefined;
      let lottiePixels: Uint8Array | undefined;
      for (const id of CASE_IDS) {
        this.setState({ status: `RUNNING ${id}` });
        const capture = await this.capture(id);
        if (id === 'label-iiii') textPixels = capture.pixels;
        if (id === 'label-mmmm') {
          let changed = 0;
          for (let i = 0; i < capture.pixels.length; i += 4)
            if (capture.pixels[i] !== textPixels?.[i]) changed++;
          check(capture.result.assertions, 'different text changes glyph pixels', changed > 70, changed);
        }
        if (id === 'lottie-t0') lottiePixels = capture.pixels;
        if (id === 'lottie-t1') {
          let changed = 0;
          for (let i = 0; i < capture.pixels.length; i += 4)
            if (capture.pixels[i] !== lottiePixels?.[i] || capture.pixels[i + 1] !== lottiePixels?.[i + 1]) changed++;
          check(capture.result.assertions, 'fixed times produce different frames', changed > 400, changed);
        }
        capture.result.passed = capture.result.assertions.every(assertion => assertion.passed);
        this.results.push(capture.result);
        this.emit({ schema: 1, kind: 'case', status: capture.result.passed ? 'RUNNING' : 'FAIL',
          result: capture.result, pngBase64: base64(new Uint8Array(capture.png)), width: WIDTH, height: HEIGHT });
        this.setState({ preview: makeAssetFromBytes(capture.png) });
      }
      const passed = this.results.length === CASE_IDS.length && this.results.every(result => result.passed);
      this.emit({ schema: 1, kind: 'finished', status: passed ? 'PASS' : 'FAIL',
        engine, provenance: PROVENANCE, expectedCaseIds: CASE_IDS, cases: this.results });
      this.setState({ status: `${passed ? 'PASS' : 'FAIL'} ${this.results.filter(result => result.passed).length}/${CASE_IDS.length}` });
    } catch (error: any) {
      if (!this.destroyed) {
        this.emit({ schema: 1, kind: 'finished', status: 'FAIL', engine, provenance: PROVENANCE,
          expectedCaseIds: CASE_IDS, cases: this.results, error: error?.stack ?? String(error) });
        this.setState({ status: `FAIL ${error?.message ?? String(error)}` });
      }
    }
  }
}
